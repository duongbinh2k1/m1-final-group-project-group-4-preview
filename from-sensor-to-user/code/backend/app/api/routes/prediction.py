"""
Prediction API Route
====================
Exposes the latest Open-Meteo weather forecast and proactive control
recommendations generated by the predictor service.

GET /api/prediction   — current outside conditions + 4h forecast + recommendations
"""

from fastapi import APIRouter

from app.core.store import store

router = APIRouter(prefix="/prediction", tags=["prediction"])


@router.get("")
def get_prediction():
    """
    Latest 4-hour outside weather forecast and proactive control recommendations.
    Data is refreshed every 30 minutes from the Open-Meteo API.
    Returns an 'available: false' message if the first fetch has not completed yet.
    """
    pred = store.prediction
    if pred is None:
        return {
            "available": False,
            "message":   (
                "Weather forecast not ready yet — "
                "the backend fetches from Open-Meteo on startup. "
                "Please wait a moment and refresh."
            ),
        }
    return {"available": True, **pred}
